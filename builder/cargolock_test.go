package builder_test

import (
	"os"
	"strings"
	"testing"

	"github.com/igorrius/ganglion/builder"
)

func TestTheExamplesLockParses(t *testing.T) {
	raw, err := os.ReadFile("../examples/modules/deye-reader/Cargo.lock")
	if err != nil {
		t.Fatal(err)
	}
	crates, err := builder.ParseCargoLock(raw)
	if err != nil {
		t.Fatal(err)
	}
	if len(crates) != strings.Count(string(raw), "[[package]]") {
		t.Fatalf("%d crates", len(crates))
	}
	roots := 0
	for _, c := range crates {
		switch {
		case c.Source == "" && c.Name == "deye-reader" && c.Checksum == "":
			roots++
		case c.Source != builder.CratesIO || len(c.Checksum) != 64 || c.Version == "":
			t.Fatalf("crate %+v", c)
		}
	}
	if roots != 1 {
		t.Fatalf("%d roots", roots)
	}
}

const smallLock = `# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 4

[[package]]
name = "cfg-if"
version = "1.0.5"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "4e7648175b45a9a48536d676f68d918270699102aa8dab5496df06904c914600"

[[package]]
name = "m"
version = "0.1.0"
dependencies = [
 "cfg-if",
]
`

func TestParseCargoLock(t *testing.T) {
	crates, err := builder.ParseCargoLock([]byte(smallLock))
	if err != nil {
		t.Fatal(err)
	}
	want := []builder.Crate{
		{Name: "cfg-if", Version: "1.0.5", Source: builder.CratesIO, Checksum: "4e7648175b45a9a48536d676f68d918270699102aa8dab5496df06904c914600"},
		{Name: "m", Version: "0.1.0"},
	}
	if len(crates) != 2 || crates[0] != want[0] || crates[1] != want[1] {
		t.Fatalf("crates %+v", crates)
	}
}

// Anything the narrow parser does not know makes the lock unreadable, so a
// build answer about it is not clean.
func TestParseCargoLockRefusesTheUnexpected(t *testing.T) {
	for name, lock := range map[string]string{
		"an unknown key":       strings.Replace(smallLock, `version = "0.1.0"`, "version = \"0.1.0\"\nreplace = \"x\"", 1),
		"a metadata table":     smallLock + "\n[metadata]\n\"checksum x\" = \"y\"\n",
		"a repeated key":       strings.Replace(smallLock, `version = "0.1.0"`, "version = \"0.1.0\"\nversion = \"0.2.0\"", 1),
		"no version":           strings.Replace(smallLock, "version = \"0.1.0\"\n", "", 1),
		"no name":              strings.Replace(smallLock, "name = \"m\"\n", "", 1),
		"an escape":            strings.Replace(smallLock, `name = "m"`, `name = "m\" x"`, 1),
		"a bare value":         strings.Replace(smallLock, `name = "m"`, `name = m`, 1),
		"a dependency":         strings.Replace(smallLock, ` "cfg-if",`, ` cfg-if`, 1),
		"an open list":         strings.Replace(smallLock, "]\n", "", 1),
		"a comment in a block": strings.Replace(smallLock, `name = "m"`, "# x\nname = \"m\"", 1),
		"no packages":          "version = 4\n",
		"a lock version later": strings.Replace(smallLock, "\nversion = 4\n", "\n", 1) + "version = 4\n",
	} {
		t.Run(name, func(t *testing.T) {
			if crates, err := builder.ParseCargoLock([]byte(lock)); err == nil {
				t.Fatalf("parsed %+v", crates)
			}
		})
	}
}

func TestPackageName(t *testing.T) {
	for toml, want := range map[string]string{
		"[package]\nname = \"blink\"\nversion = \"0.1.0\"\n":                   "blink",
		"[lib]\nname = \"x\"\n\n[package]\nedition = \"2021\"\nname = \"m\"\n": "m",
		"[package]\nname=\"m\"\n":                                              "m",
	} {
		got, err := builder.PackageName([]byte(toml))
		if err != nil || got != want {
			t.Fatalf("%q: %q, %v", toml, got, err)
		}
	}
	for _, toml := range []string{"", "[package]\nversion = \"1\"\n", "[package]\nname = 'm'\n", "[package]\nname.workspace = true\n",
		"[package]\n[lib]\nname = \"x\"\n", "[package]\nname = \"a\"\nname = \"b\"\n"} {
		if got, err := builder.PackageName([]byte(toml)); err == nil {
			t.Fatalf("%q: %q", toml, got)
		}
	}
}
